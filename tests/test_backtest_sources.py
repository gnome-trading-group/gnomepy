def test_jar_versions_reads_each_packed_pom(tmp_path):
    jar = _engine_jar(tmp_path / "engine.jar")
    assert jar_versions(jar) == {"gnome-backtest": "1.5.1", "gnome-strategies": "1.9.0", "gnome-oms": "1.13.4"}


def test_describe_engine_finds_the_gnome_backtest_jar(tmp_path):
    other = tmp_path / "other.jar"
    with zipfile.ZipFile(other, "w") as zf:
        zf.writestr("a.txt", "x")
    jar = _engine_jar(tmp_path / "engine.jar")
    described = describe_engine([str(tmp_path / "classes"), str(other), str(jar)])
    assert described.engine_jar == str(jar)
    assert described.engine_version == "1.5.1"
    assert described.runtime_version == "1.9.0"
    assert described.oms_version == "1.13.4"
    assert described.engine_jar_hash.startswith("sha256:")


def test_drift_warning_names_only_what_differs():
    engine = BacktestSources(
        classpath=[], engine_version="1.5.1", runtime_version="1.9.0", oms_version="1.13.4",
        platform_orchestrator="1.40.1",
    )
    assert drift_warning(engine, {"runtime": "1.9.0", "oms": "1.13.4"}) is None
    warning = drift_warning(engine, {"runtime": "1.9.0", "oms": "1.13.3"})
    assert "gnome-oms 1.13.4 (orchestrator 1.40.1 runs 1.13.3)" in warning
    assert "gnome-strategies" not in warning


