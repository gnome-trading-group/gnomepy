class _Tarball:
    status_code = 200

    def __init__(self, data: bytes):
        self.raw = io.BytesIO(data)

    def raise_for_status(self):
        pass


def _tarball(sha: str) -> bytes:
    buf = io.BytesIO()
    top = f"gnome-trading-group-gnome-strategies-{sha[:7]}"
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for name, text in (
            (f"{top}/strategies/pom.xml", POM),
            (f"{top}/strategies/src/main/java/A.java", "class A {}"),
            (f"{top}/runtime/pom.xml", "<project/>"),
        ):
            data = text.encode()
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def test_a_commit_fetch_keeps_only_strategies(monkeypatch):
    sha = "a" * 40
    calls = []

    def fake_github(path, accept, stream=False):
        calls.append(path)
        return _Tarball(_tarball(sha))

    monkeypatch.setattr(sources, "_github", fake_github)
    module = sources._fetch_strategies(sha)
    assert sorted(str(p.relative_to(module)) for p in module.rglob("*") if p.is_file()) == [
        "pom.xml", "src/main/java/A.java",
    ]
    assert sources._fetch_strategies(sha) == module
    assert calls == [f"gnome-strategies/tarball/{sha}"]


def test_run_rejects_a_commit_and_a_source_together(tmp_path):
    config = tmp_path / "c.yaml"
    config.write_text("start_date: 2026-01-01\n")
