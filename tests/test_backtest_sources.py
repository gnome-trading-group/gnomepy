@needs_javac
def test_local_source_compiles_the_working_tree_and_reports_it_dirty(tmp_path, monkeypatch):
    engine = _engine_jar(tmp_path / "engine.jar")
    monkeypatch.setenv("GNOME_JARS", str(engine))
    monkeypatch.setattr(sources, "orchestrator_versions", lambda version: {"runtime": "1.9.0", "oms": "1.13.4"})
    root = _strategies_checkout(tmp_path / "gnome-strategies")
    _git(root, "init", "-q")
    _git(root, "add", ".")
    _git(root, "commit", "-qm", "init")
    head = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()

    clean = prepare_sources(strategy_source=root)
    assert clean.strategy_source == "local"
    assert clean.strategy_commit == head
    assert clean.strategy_dirty is False
    assert clean.platform_orchestrator == "1.40.1"
    assert clean.warnings == []
    classes = Path(clean.classpath[-1])
    assert clean.classpath[0] == str(engine)
    assert (classes / "group/gnometrading/strategies/check/Marker.class").is_file()
    assert (classes / "marker.properties").read_text() == "name=marker\n"

    java = root / "strategies/src/main/java/group/gnometrading/strategies/check/Marker.java"
    java.write_text(STRATEGY.replace("name;", "name; // edited"))
    edited = prepare_sources(strategy_source=root)
    assert edited.strategy_dirty is True
    assert Path(edited.classpath[-1]) != classes


