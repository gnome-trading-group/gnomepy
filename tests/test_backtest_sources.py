needs_javac = pytest.mark.skipif(shutil.which("javac") is None, reason="javac not installed")


def _engine_jar(path: Path, backtest: str = "1.5.1", runtime: str = "1.9.0", oms: str = "1.13.4") -> Path:
    with zipfile.ZipFile(path, "w") as zf:
        for artifact, version in (("gnome-backtest", backtest), ("gnome-strategies", runtime), ("gnome-oms", oms)):
            zf.writestr(
                f"META-INF/maven/group.gnometrading/{artifact}/pom.properties",
                f"#Generated by Maven\nartifactId={artifact}\ngroupId=group.gnometrading\nversion={version}\n",
            )
    return path


def _strategies_checkout(root: Path) -> Path:
    module = root / "strategies"
    java = module / "src" / "main" / "java" / "group" / "gnometrading" / "strategies" / "check"
    java.mkdir(parents=True)
    (java / "Marker.java").write_text(STRATEGY)
    resources = module / "src" / "main" / "resources"
    resources.mkdir(parents=True)
    (resources / "marker.properties").write_text("name=marker\n")
    (module / "pom.xml").write_text(POM)
    return root


def _git(root: Path, *args: str) -> None:
    subprocess.run(
        ["git", "-C", str(root), "-c", "user.email=t@t", "-c", "user.name=t", *args],
        check=True, capture_output=True,
    )


